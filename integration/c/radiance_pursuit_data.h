#ifndef RADIANCE_PURSUIT_DATA_H
#define RADIANCE_PURSUIT_DATA_H
enum {
    PURSUIT_RUN_SLOT=94, PURSUIT_BRAKE_SLOT=96,
    PURSUIT_FIRST_SLOT=100, PURSUIT_SECOND_SLOT=109,
    PURSUIT_RUN_FRAMES=98, PURSUIT_LOOP_START=28, PURSUIT_LOOP_FRAMES=68,
    PURSUIT_ARRIVAL_START=21, PURSUIT_BRAKE_FRAMES=42, PURSUIT_FIRST_BRANCH=21, PURSUIT_FIRST_FRAMES=58,
    PURSUIT_SECOND_FRAMES=46, PURSUIT_SECOND_HIT_BEGIN=5, PURSUIT_SECOND_HIT_END=13,
    PURSUIT_WEAPON_SLOT=208, PURSUIT_WEAPON_FRAME=31,
    PURSUIT_FIRST_OFFSET=18, PURSUIT_SECOND_OFFSET=37
};
static inline float pursuit_brake_elapsed(float frame){return frame>=PURSUIT_ARRIVAL_START?frame-PURSUIT_ARRIVAL_START:frame;}
static inline unsigned radiance_pursuit_pose(unsigned motion)
{
    unsigned slot=motion-0x500;
    return slot==PURSUIT_RUN_SLOT||slot==PURSUIT_BRAKE_SLOT||slot==PURSUIT_FIRST_SLOT||slot==PURSUIT_SECOND_SLOT;
}
#endif

