#ifndef RADIANCE_PURSUIT_DATA_H
#define RADIANCE_PURSUIT_DATA_H
enum {
    PURSUIT_RUN_SLOT=94, PURSUIT_BRAKE_SLOT=96,
    PURSUIT_FIRST_SLOT=100, PURSUIT_SECOND_SLOT=109, PURSUIT_HANDOFF_SLOT=112,
    PURSUIT_HANDOFF_LATE_SLOT=113,
    PURSUIT_HANDOFF_FRAMES=82, PURSUIT_HANDOFF_STEP=23, PURSUIT_HANDOFF_READY=81,
    PURSUIT_RUN_FRAMES=98, PURSUIT_LOOP_START=28, PURSUIT_LOOP_FRAMES=68,
    PURSUIT_ARRIVAL_START=21, PURSUIT_BRAKE_FRAMES=42, PURSUIT_FIRST_BRANCH=21, PURSUIT_FIRST_FRAMES=58,
    PURSUIT_FIRST_HIT_BEGIN=10, PURSUIT_FIRST_HIT_END=22,
    PURSUIT_SECOND_FRAMES=46, PURSUIT_SECOND_HIT_BEGIN=0, PURSUIT_SECOND_HIT_END=16,
    PURSUIT_WEAPON_SLOT=208, PURSUIT_WEAPON_FRAME=31,
    PURSUIT_FIRST_OFFSET=18, PURSUIT_SECOND_OFFSET=37
};
static inline float pursuit_brake_elapsed(float frame){return frame>=PURSUIT_ARRIVAL_START?frame-PURSUIT_ARRIVAL_START:frame;}
static inline unsigned radiance_pursuit_handoff_slot(unsigned slot)
{
    return slot==PURSUIT_HANDOFF_SLOT||slot==PURSUIT_HANDOFF_LATE_SLOT;
}
static inline unsigned radiance_pursuit_pose(unsigned motion)
{
    unsigned slot=motion-0x500;
    return radiance_pursuit_handoff_slot(slot)||slot==PURSUIT_RUN_SLOT||slot==PURSUIT_BRAKE_SLOT||
        slot==PURSUIT_FIRST_SLOT||slot==PURSUIT_SECOND_SLOT;
}
#endif

